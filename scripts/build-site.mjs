// After `vite build -c vite.site.config.ts`:
//  1. copies the knowledge-base folder (towboat-kb/) into the site, and makes kb/kb-data.json
//     (every .md and .csv file, plus the list of documents) for the app to read;
//  2. removes the copies kept for no signal from phones that had them (the knowledge base's own, kb/sw.js, and
//     the old engine log's at the site's top address). Not needed once the site is on Vercel: delete this part then.
import { execSync } from 'node:child_process';
import { cpSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const DIR = 'dist-site';
const KB_SRC = 'towboat-kb';
const sh = (cmd) => { try { return execSync(cmd, { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch { return ''; } };
const posix = (p) => p.split('\\').join('/');
const walk = (d, out = []) => {
  for (const f of readdirSync(d)) { const p = join(d, f); statSync(p).isDirectory() ? walk(p, out) : out.push(p); }
  return out;
};

// ---------- 1. knowledge-base data ----------
const repoFull = process.env.GITHUB_REPOSITORY || (/github\.com[:/](.+?)(\.git)?$/.exec(sh('git remote get-url origin'))?.[1] ?? 'owner/repo');
const [owner, repo] = repoFull.split('/');
const branch = process.env.GITHUB_REF_NAME || sh('git rev-parse --abbrev-ref HEAD') || 'main';
const builtAt = new Date(sh('git log -1 --format=%cI') || Date.now()).toISOString(); // in UTC, like GitHub's own times
const files = [], docs = [];
for (const p of walk(KB_SRC)) {
  const rel = posix(relative(KB_SRC, p));
  if (/\.(md|csv)$/i.test(rel)) files.push({ path: rel, text: readFileSync(p, 'utf8') });
  else docs.push({ path: rel, size: statSync(p).size });
}
files.sort((a, b) => a.path.localeCompare(b.path));
docs.sort((a, b) => a.path.localeCompare(b.path));
writeFileSync(join(DIR, 'kb', 'kb-data.json'), JSON.stringify({ builtAt, owner, repo, branch, root: KB_SRC, files, docs }));
cpSync(KB_SRC, join(DIR, 'kb', 'files'), { recursive: true });

// ---------- 2. retire the no-signal copies ----------
// The site no longer keeps a copy on the phone. Phones that have one ask for these files on their next visit:
// each one deletes the kept copy, steps aside and reloads the page, which then comes straight from the site.
// Only caches this site made are deleted (other sites under the same github.io address keep theirs).
const retire = (what) => `// Removes ${what} kept on this phone for no signal. Generated by scripts/build-site.mjs.
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith('kb-') || k.startsWith('engine-log-') || k === 'fonts') await caches.delete(k);
    await self.registration.unregister();
    for (const c of await self.clients.matchAll({ type: 'window' })) c.navigate(c.url).catch(() => {});
  })());
});
`;
writeFileSync(join(DIR, 'kb', 'sw.js'), retire('the knowledge base copy'));
// The old engine log used to live at the site's top address (which now forwards to kb/).
writeFileSync(join(DIR, 'sw.js'), retire("the old engine log's copy"));
// Phones running a very early engine-log helper get its page at /kb/ too; that page then asks for its script
// here. Answer with a small script that updates that helper (to the one above) and reloads.
mkdirSync(join(DIR, 'kb', 'assets'), { recursive: true });
writeFileSync(join(DIR, 'kb', 'assets', 'index-DQUD1dTX.js'), `(async () => {
  try {
    const r = await navigator.serviceWorker.getRegistration('../');
    await r?.update();
    const w = r?.installing || r?.waiting;
    if (w) await new Promise((ok) => { const f = () => w.state === 'activated' && ok(); w.addEventListener('statechange', f); f(); setTimeout(ok, 8000); });
  } catch {}
  if (!sessionStorage.getItem('kb-recover')) { sessionStorage.setItem('kb-recover', '1'); location.reload(); }
})();
`);
console.log(`knowledge base: ${files.length} text files, ${docs.length} documents (${branch} @ ${builtAt})`);
